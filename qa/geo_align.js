const hexAt = (c, r) => g.map.hexes.get(Hex.key(c, r));

/* 城镇格 → 1 环非城镇格多数地形；非城镇格直接返回本地形 */
function siteTerrain(c, r) {
  const h = hexAt(c, r);
  if (!h) return '(无格)';
  if (h.terrain !== 'town') return h.terrain;
  const cnt = {};
  for (const n of Hex.neighbors(c, r)) {
    const nh = hexAt(n.c, n.r);
    if (nh && nh.terrain !== 'town') cnt[nh.terrain] = (cnt[nh.terrain] || 0) + 1;
  }
  const arr = Object.keys(cnt).sort((a, b) => cnt[b] - cnt[a]);
  if (!arr.length) return 'town(孤立)';
  return 'town(' + arr.slice(0, 2).map(k => k + '×' + cnt[k]).join(',') + ')';
}

